class Castchar{
    public static void main(String[] args){
        char s='A';
        int b=s;
        System.out.println(s);
        System.out.println(b);
        double dou=10.2345;
        int val=(int)dou;
        System.out.println(dou);
        System.out.println(val);
        int n=50;
        char h=(char)n;
        System.out.println(n);
        System.out.println(h);
        float t=3.14f;
        byte m=(byte)t;
        System.out.println(t);
        System.out.println(m);
    } 
}